/**
 * ASSET 2.1 PC Serial Port Bridge Service
 *
 * Responsibilities:
 * 1. Listens to the serial port of the ASSET 2.1 Hub (central Deneyap board) connected over USB.
 * 2. Captures incoming binary or JSON packets (AssetPacket - 13 bytes or JSON).
 * 3. Validates packet integrity using CRC-8.
 * 4. Forwards parsed telemetry to the local backend ingest API (/api/sensors/ingest).
 * 5. Threshold sync from the backend: when a connection is established AND when the config:updated event
 *    arrives, writes the THRESHOLD:<val>\n command to firmware over the serial port.
 *
 * Usage:
 * node bridge.js --port=/dev/ttyUSB0 --baud=115200
 * node bridge.js --mock (simulates a virtual serial stream when no hardware is connected)
 */

const path = require("path");
require("dotenv").config({ path: path.join(__dirname, "..", ".env") });
const http = require("http");

if (!process.env.INGEST_API_KEY) {
  console.error("INGEST_API_KEY is not set; check your environment configuration.");
  process.exit(1);
}

const BACKEND_HOST = process.env.BACKEND_HOST || "localhost";
const BACKEND_PORT = process.env.BACKEND_PORT || 5000;
const INGEST_PATH = "/api/sensors/ingest";
const THRESHOLDS_PATH = "/api/config/thresholds";
const INGEST_API_KEY = process.env.INGEST_API_KEY;
const ADMIN_API_KEY = process.env.ADMIN_API_KEY || "";

if (!ADMIN_API_KEY) {
  console.warn("WARNING: ADMIN_API_KEY is not set; threshold sync (GET /api/config/thresholds) may return 503.");
}

// ── Multi-port and auto-detection configuration ──
const rawPortArg = process.argv.find((arg) => arg.startsWith("--port=") || arg.startsWith("--ports="))?.split("=")[1];
const baudRate = parseInt(process.argv.find((arg) => arg.startsWith("--baud="))?.split("=")[1] || "115200");
const isMock = process.argv.includes("--mock");

// ── CRC-8 Dallas/Maxim calculator ──
function calculateCrc8(buffer) {
  let crc = 0x00;
  for (let i = 0; i < buffer.length; i++) {
    crc ^= buffer[i];
    for (let j = 0; j < 8; j++) {
      if (crc & 0x80) {
        crc = ((crc << 1) ^ 0x07) & 0xff;
      } else {
        crc = (crc << 1) & 0xff;
      }
    }
  }
  return crc;
}

// ── 13-byte AssetPacket binary parser ──
function parseAssetPacket(buf) {
  if (buf.length < 13) {
    throw new Error(`Incomplete packet length: ${buf.length} bytes (13 bytes expected)`);
  }

  const payload = buf.subarray(0, 12);
  const receivedCrc = buf[12];
  const computedCrc = calculateCrc8(payload);

  if (receivedCrc !== computedCrc) {
    console.warn(`⚠️ CRC mismatch: received=0x${receivedCrc.toString(16)}, calculated=0x${computedCrc.toString(16)}`);
  }

  const schemaVersion = buf.readUInt8(0);
  const deviceId = buf.readUInt8(1);
  const tempCx10 = buf.readUInt16LE(2);
  const tempC = parseFloat((tempCx10 / 10.0).toFixed(1));
  const humidityPct = buf.readUInt8(4);
  const smokeRaw = buf.readUInt16LE(5);
  const seqNo = buf.readUInt32LE(7);
  const batteryPct = buf.readUInt8(11);

  return {
    schemaVersion,
    deviceId: String(deviceId),
    tempC,
    humidityPct,
    smokeRaw,
    seqNo,
    batteryPct,
    crcOk: receivedCrc === computedCrc,
  };
}

// ── Packet deduplication ──
const lastSeenSeq = {};

// ── Forward to backend ──
function forwardToBackend(packet, portName = "Unknown") {
  // BINARY packets with CRC errors are never forwarded to the backend, preventing invalid readings
  // from entering fusion/SensorLog as real readings. The crcOk field is only
  // generated by the binary (26-hex / mock) path; JSON and text-fallback
  // paths leave it undefined, so this check does not affect them (=== false).
  if (packet && packet.crcOk === false) {
    console.error(
      `🚫 [CRC Rejected] Node #${packet.deviceId} (${portName}): CRC-8 mismatch; packet not sent to backend (Seq=${packet.seqNo}).`
    );
    return;
  }
  // BLE advertisements and multiple ports repeat many times per second. Filter duplicate seqNo values:
  if (packet.deviceId && packet.seqNo !== undefined) {
    if (lastSeenSeq[packet.deviceId] === packet.seqNo) {
      return;
    }
    lastSeenSeq[packet.deviceId] = packet.seqNo;
  }

  const postData = JSON.stringify(packet);

  const req = http.request(
    {
      hostname: BACKEND_HOST,
      port: BACKEND_PORT,
      path: INGEST_PATH,
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Content-Length": Buffer.byteLength(postData),
        "x-api-key": INGEST_API_KEY,
      },
    },
    (res) => {
      let body = "";
      res.on("data", (chunk) => (body += chunk));
      res.on("end", () => {
        if (res.statusCode >= 200 && res.statusCode < 300) {
          console.log(`✅ [Forwarded] Node #${packet.deviceId} (${portName}): Smoke=${packet.smokeRaw}, Temperature=${packet.tempC}°C, Seq=${packet.seqNo}, Source=${packet.source || "hardware"}`);
        } else {
          console.error(`❌ [Backend Error ${res.statusCode}]:`, body);
        }
      });
    }
  );

  req.on("error", (err) => {
    console.error(`❌ [Forwarding Error]: Could not reach backend (${err.message})`);
  });

  req.write(postData);
  req.end();
}

// ── Active serial ports (for threshold broadcasts) ──
const openSerialPorts = [];

// ── Threshold synchronization: fetch the current smokeThreshold from the backend ──
function fetchAndSendThreshold() {
  const req = http.request(
    {
      hostname: BACKEND_HOST,
      port: BACKEND_PORT,
      path: THRESHOLDS_PATH,
      method: "GET",
      headers: {
        "x-admin-key": ADMIN_API_KEY,
      },
    },
    (res) => {
      let body = "";
      res.on("data", (chunk) => (body += chunk));
      res.on("end", () => {
        try {
          const data = JSON.parse(body);
          const threshold = data?.data?.smokeThreshold;
          if (threshold !== undefined) {
            broadcastThreshold(threshold);
          } else {
            console.warn("⚠️ [Threshold Sync] Could not retrieve smokeThreshold:", body);
          }
        } catch (e) {
          console.error("❌ [Threshold Sync] JSON parse error:", e.message);
        }
      });
    }
  );
  req.on("error", (err) => {
    console.warn(`⚠️ [Threshold Sync] Could not connect to backend: ${err.message} — firmware will continue using its local threshold.`);
  });
  req.end();
}

/**
 * Writes the THRESHOLD:<val>\n command to all open serial ports.
 * @param {number} value
 */
function broadcastThreshold(value) {
  const cmd = `THRESHOLD:${value}\n`;
  if (isMock) {
    console.log(`[Threshold Sync][MOCK] Command to send to firmware: ${cmd.trim()}`);
    return;
  }
  if (openSerialPorts.length === 0) {
    console.warn("⚠️ [Threshold Sync] No open serial ports found.");
    return;
  }
  openSerialPorts.forEach(({ path, port }) => {
    if (port && port.isOpen) {
      port.write(cmd, (err) => {
        if (err) {
          console.error(`❌ [Threshold Sync] (${path}) Write error: ${err.message}`);
        } else {
          console.log(`🔧 [Threshold Sync] (${path}) Sent: ${cmd.trim()} (backend smokeThreshold: ${value})`);
        }
      });
    }
  });
}

// ── Socket.io connection: listen for the config:updated event ──
function connectSocketForThresholdSync() {
  try {
    if (!ADMIN_API_KEY) {
      // The socket requires a key: a keyless connection joins the public room on the server,
      // where config:updated is never delivered. Rather than silently falling back to public,
      // the socket is not created; the initial threshold fetch is attempted over HTTP (a visible
      // warning is logged above when needed).
      console.warn("⚠️ [Threshold Sync] ADMIN_API_KEY is not set; live threshold synchronization (config:updated) is disabled. Attempting the initial HTTP fetch...");
      setTimeout(() => fetchAndSendThreshold(), 2000);
      return;
    }

    const { io: ioClient } = require("socket.io-client");
    const backendUrl = `http://${BACKEND_HOST}:${BACKEND_PORT}`;
    // Handshake authentication: config:updated, which is used for threshold synchronization,
    // is a protected event; the key is carried in the auth payload (not URL/query and
    // not logged). The server rejects connections with an invalid key.
    const socket = ioClient(backendUrl, {
      reconnection: true,
      reconnectionDelay: 3000,
      auth: { key: ADMIN_API_KEY },
    });

    socket.on("connect", () => {
      console.log(`🔗 [Socket] Connected to backend (${backendUrl}) — listening for config:updated.`);
      console.log("🔄 [Threshold Sync] Connected; fetching the current threshold...");
      fetchAndSendThreshold();
    });

    socket.on("config:updated", (newConfig) => {
      const threshold = newConfig?.smokeThreshold;
      if (threshold !== undefined) {
        console.log(`📡 [config:updated] New smokeThreshold: ${threshold} — sending to firmware...`);
        broadcastThreshold(threshold);
      }
    });

    socket.on("disconnect", () => {
      console.warn("🔌 [Socket] Backend connection lost; reconnecting...");
    });

    socket.on("connect_error", (err) => {
      console.warn(`⚠️ [Socket] Connection error: ${err.message}`);
    });
  } catch (e) {
    if (e.code === "MODULE_NOT_FOUND") {
      console.warn("⚠️ [Threshold Sync] socket.io-client not found. Attempting initial synchronization over HTTP...");
      setTimeout(() => fetchAndSendThreshold(), 2000);
    } else {
      console.error("❌ [Socket] Unexpected error:", e.message);
    }
  }
}

// ── Mock or physical port startup ──
if (isMock) {
  console.log("==================================================");
  console.log("🛰️ ASSET 2.1 PC Serial Port Bridge Service");
  console.log(`📡 Backend target: http://${BACKEND_HOST}:${BACKEND_PORT}`);
  console.log("🔌 Operating mode: MOCK (virtual stream)");
  console.log("==================================================");
  console.log("ℹ️ No hardware connected. Simulated packets will be generated and sent every five seconds...");

  connectSocketForThresholdSync();

  let seq = 1;
  setInterval(() => {
    for (let id = 1; id <= 5; id++) {
      seq++;
      const buf = Buffer.alloc(13);
      buf.writeUInt8(0x01, 0); // schema version
      buf.writeUInt8(id, 1);   // device_id
      buf.writeUInt16LE(Math.round((24.0 + Math.random()) * 10), 2); // temp_c_x10
      buf.writeUInt8(Math.round(50 + Math.random() * 5), 4); // humidity_pct
      buf.writeUInt16LE(Math.round(250 + Math.random() * 50), 5); // smoke_raw
      buf.writeUInt32LE(seq, 7); // seq_no
      buf.writeUInt8(95, 11); // battery_pct
      const crc = calculateCrc8(buf.subarray(0, 12));
      buf.writeUInt8(crc, 12); // crc8

      try {
        const parsed = parseAssetPacket(buf);
        parsed.source = "mock";
        forwardToBackend(parsed, "MOCK");
      } catch (err) {
        console.error("Packet parse error:", err);
      }
    }
  }, 5000);
} else {
  // Physical serial port management
  (async () => {
    try {
      const { SerialPort } = require("serialport");
      const { ReadlineParser } = require("@serialport/parser-readline");

      let portPaths = [];

      if (rawPortArg) {
        // If the user provides one or more comma-separated ports: --port=/dev/ttyUSB0,/dev/ttyUSB1
        portPaths = rawPortArg.split(",").map((p) => p.trim()).filter(Boolean);
      } else {
        // If no port is specified, automatically detect all connected USB/ACM ports
        console.log("🔍 Scanning serial ports (auto-detect)...");
        const availablePorts = await SerialPort.list();
        const usbPorts = availablePorts.filter(
          (p) =>
            p.path.includes("ttyUSB") ||
            p.path.includes("ttyACM") ||
            (p.vendorId && p.vendorId.toLowerCase() === "10c4") // CP210x
        );
        portPaths = usbPorts.map((p) => p.path);
        if (portPaths.length === 0) {
          portPaths = ["/dev/ttyUSB0"]; // Fallback
        }
      }

      console.log("==================================================");
      console.log("🛰️ ASSET 2.1 PC Serial Port Bridge Service");
      console.log(`📡 Backend target: http://${BACKEND_HOST}:${BACKEND_PORT}`);
      console.log(`🔌 Listening ports: ${portPaths.join(", ")} (@ ${baudRate} baud)`);
      console.log("==================================================");

      connectSocketForThresholdSync();

      portPaths.forEach((path) => {
        try {
          const port = new SerialPort({ path, baudRate });
          const parser = port.pipe(new ReadlineParser({ delimiter: "\n" }));

          // Last-seen Node ID for this port (for text lines)
          let lastDetectedNodeId = null;

          port.on("open", () => {
            console.log(`✅ Serial port opened: ${path} (${baudRate} baud)`);
            openSerialPorts.push({ path, port });
            // Synchronize the backend threshold after ports open (debounce)
            if (global.thresholdSyncTimeout) clearTimeout(global.thresholdSyncTimeout);
            global.thresholdSyncTimeout = setTimeout(() => fetchAndSendThreshold(), 800);
          });

          parser.on("data", (line) => {
            const trimmed = line.trim();
            if (!trimmed) return;

            // Filter firmware acknowledgements
            if (trimmed.startsWith("THRESHOLD_ACK:") || trimmed.startsWith("[CONFIG]")) {
              console.log(`📟 [Firmware][${path}]: ${trimmed}`);
              return;
            }

            // Capture the node ID from the firmware startup message.
            const initMatch = trimmed.match(/Node\s*#(\d+)/i);
            if (initMatch) {
              lastDetectedNodeId = initMatch[1];
            }

            console.log(`📥 [${path}]: ${trimmed}`);

            // 1. If the input is JSON (hub or node JSON output)
            if (trimmed.startsWith("{") && trimmed.endsWith("}")) {
              try {
                const json = JSON.parse(trimmed);
                if (!json.source) json.source = "hardware";
                if (json.deviceId) {
                  lastDetectedNodeId = String(json.deviceId);
                }
                forwardToBackend(json, path);
              } catch (e) {
                console.error(`❌ [${path}] JSON parse error:`, e.message);
              }
            }
            // 2. If the input is a 26-character hex string (binary AssetPacket)
            else if (/^[0-9a-fA-F]{26}$/.test(trimmed)) {
              try {
                const buf = Buffer.from(trimmed, "hex");
                const packet = parseAssetPacket(buf);
                packet.source = "hardware";
                if (packet.deviceId) {
                  lastDetectedNodeId = String(packet.deviceId);
                }
                forwardToBackend(packet, path);
              } catch (e) {
                console.error(`❌ [${path}] HEX parse error:`, e.message);
              }
            }
            // 3. Legacy Turkish serial fallback format. These labels are parsed below and are part of the existing text protocol.
            // Firmware also prints JSON immediately afterward; use this fallback when JSON is unavailable:
            else if (trimmed.includes("[Seq #")) {
              try {
                const seqMatch = trimmed.match(/\[Seq #(\d+)\]/);
                const smokeMatch = trimmed.match(/Telafili Duman:\s*(\d+)/);
                const tempMatch = trimmed.match(/Sıcaklık:\s*([\d\.]+)°C/);
                const humidityMatch = trimmed.match(/Nem:\s*([\d\.]+)%/);

                // If JSON was previously received or detected on this port, use its Node ID
                if (smokeMatch && tempMatch && humidityMatch && lastDetectedNodeId) {
                  const packet = {
                    deviceId: String(lastDetectedNodeId),
                    seqNo: seqMatch ? parseInt(seqMatch[1]) : 1,
                    smokeRaw: parseInt(smokeMatch[1]),
                    tempC: parseFloat(tempMatch[1]),
                    humidityPct: parseFloat(humidityMatch[1]),
                    batteryPct: 95,
                    source: "hardware",
                  };
                  forwardToBackend(packet, path);
                }
              } catch (e) {
                console.error(`❌ [${path}] Text parse error:`, e.message);
              }
            }
          });

          port.on("error", (err) => {
            console.error(`❌ Serial port error (${path}): ${err.message}`);
          });

          port.on("close", () => {
            console.warn(`🔌 Serial port closed: ${path}`);
            const idx = openSerialPorts.findIndex((p) => p.path === path);
            if (idx !== -1) openSerialPorts.splice(idx, 1);
          });
        } catch (err) {
          console.error(`❌ Error opening port (${path}):`, err.message);
        }
      });
    } catch (e) {
      console.warn(`⚠️ Could not start serial port: ${e.message}`);
      if (e.code === "MODULE_NOT_FOUND") {
        console.log("👉 Fix: from the backend directory, 'npm install serialport @serialport/parser-readline' run this command.");
      }
      console.log("ℹ️ To test without hardware: node bridge/bridge.js --mock");
    }
  })();
}
